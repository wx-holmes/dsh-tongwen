/** 任务文本命中哪些墙（简单包含匹配；宁可漏，不乱贴） */
export function detectWalls(taskText) {
  const text = String(taskText ?? '')
  if (!text) return []
  return WALLS.filter((wall) => wall.triggers.some((key) => text.includes(key)))
}

/** 把一面墙排成回执里的样子（≤6 行 + 出处一行） */
export function wallText(wall) {
  return [
    `【墙 · ${wall.label}】你正要过这堵墙，墙上只有 ${wall.lines.length - 1} 条，读完不用再翻整页：`,
    ...wall.lines,
    `（要细看：${wall.doc}）`,
  ].join('\n')
}

/** 给工具回执用的短版：只报墙名 + 第一条，诱它自己翻 */
export function wallTeaser(wall) {
  return `【墙 · ${wall.label}】${wall.lines[0]} —— 另有 ${wall.lines.length - 2} 条，需要就 focus_context{task:"${wall.label.replace('的墙', '')}"}`
}
